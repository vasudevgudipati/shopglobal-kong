#!/bin/bash
# Prints the PROD edge nginx.conf. Inputs are environment variables (set by jenkins/prod/edge.Jenkinsfile):
#   HTTPS_PORT, API_HOST, API_UPSTREAMS (space separated host:port list)
#   WEB_HOST/WEB_UPSTREAM, AGENT_HOST/AGENT_UPSTREAM, AI_HOST/AI_UPSTREAM  (a name is published only when its upstream is set)
set -euo pipefail
PORT=${HTTPS_PORT:-8443}

upstream() {   # name, then host:port entries
  local name=$1; shift
  echo "  upstream $name {"
  for s in "$@"; do echo "    server $s max_fails=2 fail_timeout=10s;"; done
  echo "    keepalive 32;"
  echo "  }"
}

vhost() {      # host, upstream name, kind (plain|ws|stream)
  local host=$1 up=$2 kind=$3
  cat <<EOF
  server {
    listen $PORT ssl;
    server_name $host;
    location / {
      proxy_pass http://$up;
      proxy_http_version 1.1;
      proxy_set_header Host \$host;
      proxy_set_header X-Real-IP \$remote_addr;
      proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
      proxy_set_header X-Forwarded-Proto https;
      proxy_next_upstream error timeout;
EOF
  case "$kind" in
    ws)     printf '      proxy_set_header Upgrade $http_upgrade;\n      proxy_set_header Connection $connection_upgrade;\n      proxy_read_timeout 60s;\n' ;;
    stream) printf '      proxy_set_header Connection "";\n      proxy_buffering off;          # streaming model responses\n      proxy_read_timeout 300s;\n' ;;
    *)      printf '      proxy_set_header Connection "";\n      proxy_read_timeout 60s;\n' ;;
  esac
  printf '    }\n  }\n'
}

cat <<EOF
# Generated by Jenkins (jenkins/prod/edge.Jenkinsfile). Do not edit on the server: the next run overwrites it.
worker_processes auto;
pid /run/nginx.pid;
events { worker_connections 2048; }
http {
  server_tokens off;
  client_max_body_size 20m;
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_certificate     /etc/nginx/tls/tls.crt;
  ssl_certificate_key /etc/nginx/tls/tls.key;
  access_log /var/log/nginx/access.log;
  error_log  /var/log/nginx/error.log warn;
  map \$http_upgrade \$connection_upgrade { default upgrade; '' close; }

  # Local health endpoint, used only by keepalived (not reachable from the network).
  server { listen 127.0.0.1:8081; location = /healthz { return 200 "ok\n"; } }

  # Unknown host names get nothing.
  server { listen $PORT ssl default_server; server_name _; return 404; }

EOF
# shellcheck disable=SC2086
upstream kong_api $API_UPSTREAMS
vhost "$API_HOST" kong_api plain
if [ -n "${WEB_UPSTREAM:-}" ];   then upstream web_app   $WEB_UPSTREAM;   vhost "$WEB_HOST"   web_app   ws;     fi
if [ -n "${AGENT_UPSTREAM:-}" ]; then upstream agent_app $AGENT_UPSTREAM; vhost "$AGENT_HOST" agent_app stream; fi
if [ -n "${AI_UPSTREAM:-}" ];    then upstream kong_ai   $AI_UPSTREAM;    vhost "$AI_HOST"    kong_ai   stream; fi
echo "}"
